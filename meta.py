"""
meta.py — Component schema definitions for the RM Estimator.

Equivalent to a chapter's meta.py in the Reliability app (which holds
CHAPTER_ID / chapter title / etc.) — here it holds COMPONENT_ID plus,
for each component type, the input fields to show the user and the
geometry mapping calculator.py needs.

Each schema entry has:
    fields      : list of field dicts shown to the user, in order
                  A field is mandatory unless it carries "required": False.
                  Only mark a field mandatory if the GEOMETRY needs it —
                  requiring a field the blank calculation never reads (dish
                  end Height, for instance) silently drops the row from the
                  calculation and looks like the app ignoring the part.
                  {"key": ..., "label": ..., "abbr": ..., "unit": ...,
                   "numeric": bool}
                  "label" is the full form, shown in the legend under the
                  table; "abbr" is the short form shown in the column
                  header, so wide tables stay readable.
                  optionally: "options": [...] for a fixed-choice dropdown
                  (e.g. dish end head type) instead of a free-typed value
    note        : assumption/explanation shown in the UI for this type
    blank_shape : fn(part_dict) -> shape dict, the flat piece cut from
                  the raw plate
    net_shape   : fn(part_dict) -> shape dict, the actual finished part

SHAPE DICTS (consumed by calculator.py)
    {"kind": "circle", "d": diameter}
    {"kind": "ring",   "d": outer_diameter, "di": inner_diameter}
    {"kind": "rect",   "l": length, "w": width}

INNER vs OUTER DIAMETER
    Dish End and Shell are specified by INNER diameter (ID), which is how
    vessel drawings normally dimension them. The dish end blank formulas
    are written in terms of OUTER diameter, so meta.py converts with
    OD = ID + 2t before calling the formula. The shell formula works on
    the MEAN diameter and applies (ID + t) itself.

    The Flange keeps OD and bore as reference dimensions from the flange
    database, but it is purchased as a finished component. These dimensions
    are NOT used to allocate plate material or RM cost.

WHY blank_shape AND net_shape ARE SOMETIMES DIFFERENT
    Dish End : forming (dishing) reshapes the blank without removing
               material -> blank == net.
    Shell    : rolling a flat sheet into a cylinder also removes no
               material -> blank == net.
    Flange   : purchased finished. No blank is cut and no bore scrap is
               generated by this estimator.
    Custom   : generic rectangular stand-in for a 4th component not
               yet specified -> blank == net until real geometry is
               known.

RATE
    Plate-cut components use a material rate in Rs/kg. Flanges are the
    exception: their rate is a purchase rate in Rs/pc and total cost is
    quantity x purchase rate.
"""


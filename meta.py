def _shell_blank(p):
    """Blank plate for a rolled shell: width = pi(ID + t), length = height."""
    w, l = shell_blank_plate(p["id_"], p["thk"], p["ht"])
    return {"kind": "rect", "l": l, "w": w}


def _dish_end_blank(p):
    """Blank circle for a dish end. ID -> OD conversion happens here."""
    od = outer_from_inner(p["id_"], p["thk"])
    return {"kind": "circle", "d": dish_end_development_diameter(
        od, p.get("sf"), p.get("knuckle_r"), p["head_type"], p.get("formula"))}


def _cone_dev(p):
    """The developed pattern of one cone or frustum piece."""
    d_small = 0.0 if str(p.get("cone_type") or "").lower().startswith("full") \
        else (p.get("id2_") or 0)
    return cone_development(p.get("ht"), p.get("id_"), d_small, p.get("thk"),
                            p.get("gores") or 1)


def _cone_blank(p):
    return _cone_dev(p)["shape"]


def _cone_pieces(p):
    """A cone split into gores is that many blanks per cone."""
    return max(1, int(p.get("gores") or 1))


def _ring_shape(p):
    """
    A ring's geometry, refusing the ones that cannot exist.

    Nothing used to check that the bore was smaller than the outside. Type the
    two numbers into the wrong boxes - ID 500, OD 400 - and the app built a
    ring whose "bore" was larger than the ring itself. The nester then decided
    every part on the plate fitted inside that bore, including the ring itself
    and other rings, so blanks were stacked on top of each other and pushed off
    the edge of the plate. The layout failed its own validation and was thrown
    away, and the estimate quietly fell back to a worse packing.

    That is exactly the "sometimes it is quick and the nesting is wrong"
    symptom: quick because the good layout was discarded, wrong because what
    you were shown was the fallback. A typo should be an error message, not a
    silently degraded quotation.
    """
    od = float(p.get("od") or 0.0)
    bore = float(p.get("id_") or 0.0)
    name = (p.get("part_no") or p.get("part_name") or "").strip()
    tag = f" on {name}" if name else ""
    if od <= 0:
        raise ValueError(f"Ring{tag}: outer diameter must be greater than 0.")
    if bore <= 0:
        raise ValueError(f"Ring{tag}: inner diameter must be greater than 0.")
    if bore >= od:
        raise ValueError(
            f"Ring{tag}: inner diameter ({bore:g} mm) must be smaller than the "
            f"outer diameter ({od:g} mm). Check the two are not swapped.")
    return {"kind": "ring", "d": od, "di": bore}



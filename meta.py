def get_schema(component_type: str) -> dict:
    """Return the schema dict for a component type. Raises KeyError if unknown."""
    return COMPONENT_SCHEMAS[component_type]


def list_component_types() -> list:
    return list(COMPONENT_SCHEMAS.keys())


def legend_for(component_type: str) -> list:
    """
    Abbreviation -> full form pairs for the legend shown under the input
    table. Only fields whose header is actually abbreviated are included,
    so the legend stays short and every entry earns its place.
    """
    out = []
    for f in COMPONENT_SCHEMAS[component_type]["fields"]:
        abbr = f.get("abbr", f["label"])
        if abbr != f["label"]:
            out.append({"abbr": abbr, "label": f["label"], "unit": f.get("unit", "")})
    return out
